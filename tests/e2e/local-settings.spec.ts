import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { readFile, mkdir } from 'node:fs/promises'
test('local data settings confirms deletion and previews a private-data-free diagnostic download',async({page})=>{
  const response=await page.request.post('/api/projects',{headers:{'x-shouwei-request':'local'},data:{name:'不进诊断的项目',recipient:'私有联系人',goal:'私有目标'}})
  const project=(await response.json()).data
  await page.goto('/local/storage')
  await expect(page.getByRole('heading',{name:'本机的东西，心里有数。',exact:true})).toBeVisible()
  const row=page.getByRole('article').filter({hasText:'不进诊断的项目'})
  await row.getByRole('button',{name:'删除本地项目',exact:true}).click()
  await expect(page.getByRole('button',{name:'确认删除',exact:true})).toBeDisabled()
  await page.keyboard.press('Escape')
  await expect(row).toBeVisible()
  await page.getByRole('button',{name:'预览诊断',exact:true}).click()
  const dialog=page.getByRole('dialog',{name:'诊断预览',exact:true})
  await expect(dialog).toBeVisible()
  expect(await dialog.textContent()).not.toContain('私有联系人')
  expect(await dialog.textContent()).not.toContain('不进诊断的项目')
  const download=page.waitForEvent('download')
  await dialog.getByRole('button',{name:'下载这份诊断',exact:true}).click()
  const data=await readFile((await(await download).path())!,'utf8')
  expect(JSON.parse(data).schema).toBe(1)
  expect(data).not.toContain('私有目标')
  await page.keyboard.press('Escape')
  await row.getByRole('button',{name:'删除本地项目',exact:true}).click()
  await page.getByLabel('我理解原文件、交付包和冻结报告会保留').check()
  await page.getByRole('button',{name:'确认删除',exact:true}).click()
  await expect(row).toHaveCount(0)
  expect((await page.request.get(`/api/projects/${project.id}`,{headers:{'x-shouwei-request':'local'}})).status()).toBe(404)
  await page.setViewportSize({width:375,height:900})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  expect((await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa']).analyze()).violations).toEqual([])
  await mkdir('docs/evidence/stage-5',{recursive:true})
  await page.screenshot({path:'docs/evidence/stage-5/storage-375.png',fullPage:true})
})
